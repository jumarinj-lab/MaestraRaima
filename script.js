let activeServiceIndex = 0;

function activateService(nextIndex, smooth = true) {
  activeServiceIndex = (nextIndex + serviceSlides.length) % serviceSlides.length;

  serviceSlides.forEach((slide, index) => {
    const isActive = index === activeServiceIndex;
    slide.classList.toggle('active', isActive);
    slide.setAttribute('aria-hidden', String(!isActive));
  });

  serviceNavButtons.forEach((button, index) => {
    const isActive = index === activeServiceIndex;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-selected', String(isActive));
  });

  serviceCounter.textContent = `${String(activeServiceIndex + 1).padStart(2, '0')} / ${String(serviceSlides.length).padStart(2, '0')}`;
  const activeNavButton = serviceNavButtons[activeServiceIndex];
  const targetLeft = activeNavButton.offsetLeft - serviceNavigation.clientWidth / 2 + activeNavButton.clientWidth / 2;
  serviceNavigation.scrollTo({ left: targetLeft, behavior: smooth ? 'smooth' : 'auto' });
}

previousService.addEventListener('click', () => activateService(activeServiceIndex - 1));
nextService.addEventListener('click', () => activateService(activeServiceIndex + 1));
serviceNavButtons.forEach((button, index) => {
  button.addEventListener('click', () => activateService(index));
});

serviceStage.addEventListener('keydown', (event) => {
  if (event.key === 'ArrowLeft') {
    event.preventDefault();
    activateService(activeServiceIndex - 1);
  }
  if (event.key === 'ArrowRight') {
    event.preventDefault();
    activateService(activeServiceIndex + 1);
  }
});

let serviceTouchStartX = 0;
serviceStage.addEventListener('touchstart', (event) => {
  serviceTouchStartX = event.changedTouches[0].clientX;
}, { passive: true });
serviceStage.addEventListener('touchend', (event) => {
  const distance = event.changedTouches[0].clientX - serviceTouchStartX;
  if (Math.abs(distance) > 45) {
    activateService(activeServiceIndex + (distance < 0 ? 1 : -1));
  }
}, { passive: true });

