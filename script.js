function buildWhatsAppUrl(language) {
  const message = translations[language].whatsappMessage;
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;
}

function updateWhatsAppLinks(language) {
  const url = buildWhatsAppUrl(language);
  whatsappLinks.forEach((link) => {
    link.href = url;
  });
}

function getWhatsAppPlacement(link) {
  if (link.classList.contains("floating-whatsapp")) {
    return "floating_button";
  }

  const pageArea = link.closest("section[id], header[id], footer");
  return pageArea?.id || pageArea?.tagName.toLowerCase() || "page";
}

whatsappLinks.forEach((link) => {
  link.addEventListener("click", () => {
    if (typeof window.gtag !== "function") {
      return;
    }

    window.gtag("event", "generate_lead", {
      method: "WhatsApp",
      language: currentLanguage,
      contact_location: getWhatsAppPlacement(link),
    });
  });
});

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];

  document.documentElement.lang = language;
  document.title = dictionary.pageTitle;
  metaDescription.setAttribute("content", dictionary.pageDescription);
  languageSwitch.dataset.language = language;
  languageSwitch.setAttribute("aria-label", dictionary.languageAria);

  translatableElements.forEach((element) => {
    const translationKey = element.dataset.i18n;
    if (dictionary[translationKey]) {
      element.textContent = dictionary[translationKey];
    }
  });

  languageLabels.forEach((label) => {
    label.classList.toggle("active", label.dataset.langLabel === language);
  });

  updateWhatsAppLinks(language);
  const successCasesLabel = document.querySelector('.success-seal span');
  if (successCasesLabel) {
    successCasesLabel.textContent = language === 'es' ? 'casos de éxito' : 'successful cases';
  }
  const interactiveServiceTitles = [...document.querySelectorAll('.service-slide h3')];
  document.querySelectorAll('.service-nav-item').forEach((button, index) => {
    const title = interactiveServiceTitles[index]?.textContent.trim() || '';
    const navTitle = button.querySelector('.service-nav-title');
    if (navTitle) navTitle.textContent = title;
    button.setAttribute('aria-label', title);
  });

  const previousServiceButton = document.querySelector('.service-control.previous');
  const nextServiceButton = document.querySelector('.service-control.next');
  previousServiceButton?.setAttribute(
    'aria-label',
    language === 'es' ? 'Servicio anterior' : 'Previous service',
  );
  nextServiceButton?.setAttribute(
    'aria-label',
    language === 'es' ? 'Siguiente servicio' : 'Next service',
  );
  localStorage.setItem("raima-language", language);
}

